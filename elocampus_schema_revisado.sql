-- EloCampus - esquema PostgreSQL revisado
-- Revisão 2: solicitante não precisa criar conta; identificação é feita pelo operador no empréstimo.
-- Execute em um banco vazio chamado elocampus.
-- Este arquivo não cria usuários PostgreSQL nem altera backend/app.py.
--
-- Decisões:
--   * todo equipamento possui número patrimonial;
--   * empréstimos podem conter vários equipamentos;
--   * cada item pode ser devolvido separadamente;
--   * histórico de movimentações é preservado;
--   * QR Code contém um identificador estável, não dados pessoais;
--   * solicitantes NÃO possuem login: o operador identifica a pessoa durante o empréstimo;
--   * o cadastro mínimo do solicitante pode ser criado automaticamente no primeiro empréstimo;
--   * usuários são somente operadores/administradores autenticados.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    papel VARCHAR(20) NOT NULL DEFAULT 'operador',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuarios_papel CHECK (papel IN ('admin', 'operador'))
);
COMMENT ON TABLE usuarios IS 'Contas de acesso ao EloCampus; solicitantes sem acesso ficam em solicitantes.';
COMMENT ON COLUMN usuarios.senha_hash IS 'Armazenar somente hash seguro, nunca senha em texto puro.';

CREATE TABLE IF NOT EXISTS solicitantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    identificador_institucional VARCHAR(60),
    tipo VARCHAR(30) NOT NULL DEFAULT 'outro',
    setor VARCHAR(100),
    email VARCHAR(150),
    telefone VARCHAR(30),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_solicitantes_identificador UNIQUE (identificador_institucional),
    CONSTRAINT ck_solicitantes_tipo CHECK (tipo IN ('servidor', 'professor', 'funcionario', 'estudante', 'outro'))
);
COMMENT ON TABLE solicitantes IS 'Registro mínimo de quem recebe equipamentos. Não é uma conta de usuário; o operador identifica a pessoa durante o empréstimo.';
COMMENT ON COLUMN solicitantes.identificador_institucional IS 'Matrícula, SIAPE ou outro identificador institucional, se disponível; não é obrigatório.';
COMMENT ON COLUMN solicitantes.setor IS 'Setor/unidade, quando informado. O cadastro pode ser concluído durante o primeiro empréstimo.';

CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    descricao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE categorias IS 'Classificações dos equipamentos.';

CREATE TABLE IF NOT EXISTS equipamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    numero_patrimonio VARCHAR(60) NOT NULL UNIQUE,
    categoria_id BIGINT NOT NULL,
    setor VARCHAR(100) NOT NULL,
    localizacao VARCHAR(150),
    estado_conservacao VARCHAR(30) NOT NULL DEFAULT 'bom',
    status VARCHAR(30) NOT NULL DEFAULT 'disponivel',
    qr_code_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_equipamentos_categoria FOREIGN KEY (categoria_id)
        REFERENCES categorias(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_equipamentos_estado CHECK (
        estado_conservacao IN ('novo', 'bom', 'regular', 'danificado', 'inservivel')
    ),
    CONSTRAINT ck_equipamentos_status CHECK (
        status IN ('disponivel', 'emprestado', 'manutencao', 'baixado')
    )
);
COMMENT ON TABLE equipamentos IS 'Cadastro individual dos bens patrimoniais.';
COMMENT ON COLUMN equipamentos.qr_code_id IS 'Identificador opaco para gerar URL de consulta; não contém dados pessoais.';

CREATE TABLE IF NOT EXISTS emprestimos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id BIGINT NOT NULL,
    usuario_responsavel_id BIGINT NOT NULL,
    data_emprestimo TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_prevista_devolucao TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'em_andamento',
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_emprestimos_solicitante FOREIGN KEY (solicitante_id)
        REFERENCES solicitantes(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_emprestimos_usuario FOREIGN KEY (usuario_responsavel_id)
        REFERENCES usuarios(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_emprestimos_status CHECK (status IN ('em_andamento', 'concluido', 'cancelado')),
    CONSTRAINT ck_emprestimos_prazo CHECK (data_prevista_devolucao >= data_emprestimo)
);
COMMENT ON TABLE emprestimos IS 'Cabeçalho da operação; itens e devoluções individuais ficam em itens_emprestimo.';

CREATE TABLE IF NOT EXISTS itens_emprestimo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emprestimo_id BIGINT NOT NULL,
    equipamento_id BIGINT NOT NULL,
    data_devolucao TIMESTAMPTZ,
    estado_na_retirada VARCHAR(30) NOT NULL DEFAULT 'bom',
    estado_na_devolucao VARCHAR(30),
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_itens_emprestimo_emprestimo FOREIGN KEY (emprestimo_id)
        REFERENCES emprestimos(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_itens_emprestimo_equipamento FOREIGN KEY (equipamento_id)
        REFERENCES equipamentos(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uq_itens_emprestimo_par UNIQUE (emprestimo_id, equipamento_id),
    CONSTRAINT ck_itens_estado_retirada CHECK (
        estado_na_retirada IN ('novo', 'bom', 'regular', 'danificado', 'inservivel')
    ),
    CONSTRAINT ck_itens_estado_devolucao CHECK (
        estado_na_devolucao IS NULL OR
        estado_na_devolucao IN ('novo', 'bom', 'regular', 'danificado', 'inservivel')
    ),
    CONSTRAINT ck_itens_devolucao_estado CHECK (
        (data_devolucao IS NULL AND estado_na_devolucao IS NULL) OR data_devolucao IS NOT NULL
    )
);
COMMENT ON TABLE itens_emprestimo IS 'Itens individuais de cada empréstimo; suporta devoluções em datas diferentes.';

CREATE TABLE IF NOT EXISTS manutencoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL,
    usuario_responsavel_id BIGINT,
    descricao_problema TEXT NOT NULL,
    data_abertura TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_conclusao TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'aberta',
    solucao TEXT,
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_manutencoes_equipamento FOREIGN KEY (equipamento_id)
        REFERENCES equipamentos(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_manutencoes_usuario FOREIGN KEY (usuario_responsavel_id)
        REFERENCES usuarios(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_manutencoes_status CHECK (status IN ('aberta', 'em_andamento', 'concluida', 'cancelada')),
    CONSTRAINT ck_manutencoes_datas CHECK (data_conclusao IS NULL OR data_conclusao >= data_abertura)
);
COMMENT ON TABLE manutencoes IS 'Registra problemas e reparos, preservando registros anteriores.';

CREATE TABLE IF NOT EXISTS historico_movimentacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL,
    usuario_id BIGINT,
    emprestimo_id BIGINT,
    tipo_movimentacao VARCHAR(40) NOT NULL,
    data_movimentacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    descricao TEXT NOT NULL,
    detalhes JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fk_historico_equipamento FOREIGN KEY (equipamento_id)
        REFERENCES equipamentos(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_historico_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_historico_emprestimo FOREIGN KEY (emprestimo_id)
        REFERENCES emprestimos(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_historico_tipo CHECK (tipo_movimentacao IN (
        'cadastro', 'retirada', 'devolucao', 'manutencao',
        'mudanca_localizacao', 'mudanca_status', 'ajuste', 'baixa'
    ))
);
COMMENT ON TABLE historico_movimentacoes IS 'Trilha de auditoria funcional das movimentações relevantes.';
COMMENT ON COLUMN historico_movimentacoes.detalhes IS 'Metadados não sensíveis em JSONB; não guardar senhas.';

CREATE INDEX IF NOT EXISTS idx_equipamentos_categoria ON equipamentos(categoria_id);
CREATE INDEX IF NOT EXISTS idx_equipamentos_status ON equipamentos(status);
CREATE INDEX IF NOT EXISTS idx_emprestimos_solicitante ON emprestimos(solicitante_id);
CREATE INDEX IF NOT EXISTS idx_emprestimos_status_prazo ON emprestimos(status, data_prevista_devolucao);
CREATE INDEX IF NOT EXISTS idx_itens_emprestimo_equipamento ON itens_emprestimo(equipamento_id);
CREATE INDEX IF NOT EXISTS idx_itens_emprestimo_emprestimo ON itens_emprestimo(emprestimo_id);
CREATE INDEX IF NOT EXISTS idx_manutencoes_equipamento_status ON manutencoes(equipamento_id, status);
CREATE INDEX IF NOT EXISTS idx_historico_equipamento_data ON historico_movimentacoes(equipamento_id, data_movimentacao DESC);

-- Um equipamento só pode ter um item de empréstimo não devolvido.
CREATE UNIQUE INDEX IF NOT EXISTS uq_item_equipamento_emprestimo_ativo
    ON itens_emprestimo(equipamento_id) WHERE data_devolucao IS NULL;

-- Recalcula o status operacional conforme empréstimos e manutenções.
-- Equipamento com empréstimo ativo não deve ser marcado como disponível.
CREATE OR REPLACE FUNCTION elocampus_atualizar_status_equipamento(p_equipamento_id BIGINT)
RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
    UPDATE equipamentos e
    SET status = CASE
        WHEN e.status = 'baixado' THEN 'baixado'
        WHEN EXISTS (
            SELECT 1 FROM itens_emprestimo i
            WHERE i.equipamento_id = p_equipamento_id
              AND i.data_devolucao IS NULL
        ) THEN 'emprestado'
        WHEN EXISTS (
            SELECT 1 FROM manutencoes m
            WHERE m.equipamento_id = p_equipamento_id
              AND m.status IN ('aberta', 'em_andamento')
        ) THEN 'manutencao'
        ELSE 'disponivel'
    END,
    atualizado_em = CURRENT_TIMESTAMP
    WHERE e.id = p_equipamento_id AND e.status <> 'baixado';
END;
$$;

CREATE OR REPLACE FUNCTION elocampus_trigger_item_emprestimo_status()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM elocampus_atualizar_status_equipamento(OLD.equipamento_id);
        RETURN OLD;
    END IF;
    PERFORM elocampus_atualizar_status_equipamento(NEW.equipamento_id);
    IF TG_OP = 'UPDATE' AND OLD.equipamento_id <> NEW.equipamento_id THEN
        PERFORM elocampus_atualizar_status_equipamento(OLD.equipamento_id);
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_item_emprestimo_status ON itens_emprestimo;
CREATE TRIGGER trg_item_emprestimo_status
AFTER INSERT OR UPDATE OR DELETE ON itens_emprestimo
FOR EACH ROW EXECUTE FUNCTION elocampus_trigger_item_emprestimo_status();

CREATE OR REPLACE FUNCTION elocampus_trigger_manutencao_status()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM elocampus_atualizar_status_equipamento(OLD.equipamento_id);
        RETURN OLD;
    END IF;
    PERFORM elocampus_atualizar_status_equipamento(NEW.equipamento_id);
    IF TG_OP = 'UPDATE' AND OLD.equipamento_id <> NEW.equipamento_id THEN
        PERFORM elocampus_atualizar_status_equipamento(OLD.equipamento_id);
    END IF;
    RETURN NEW;
END;
$$;

-- Não permite abrir manutenção enquanto o equipamento estiver emprestado.
CREATE OR REPLACE FUNCTION elocampus_validar_manutencao()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status IN ('aberta', 'em_andamento')
       AND EXISTS (
           SELECT 1 FROM itens_emprestimo i
           WHERE i.equipamento_id = NEW.equipamento_id
             AND i.data_devolucao IS NULL
       ) THEN
        RAISE EXCEPTION 'Não é possível abrir manutenção: equipamento % está emprestado',
            NEW.equipamento_id;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_manutencao ON manutencoes;
CREATE TRIGGER trg_validar_manutencao
BEFORE INSERT OR UPDATE OF equipamento_id, status ON manutencoes
FOR EACH ROW EXECUTE FUNCTION elocampus_validar_manutencao();

DROP TRIGGER IF EXISTS trg_manutencao_status ON manutencoes;
CREATE TRIGGER trg_manutencao_status
AFTER INSERT OR UPDATE OR DELETE ON manutencoes
FOR EACH ROW EXECUTE FUNCTION elocampus_trigger_manutencao_status();

-- Valida que um item novo não seja emprestado enquanto o equipamento estiver indisponível.
CREATE OR REPLACE FUNCTION elocampus_validar_item_emprestimo()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_status VARCHAR(30);
BEGIN
    SELECT status INTO v_status
    FROM equipamentos WHERE id = NEW.equipamento_id FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Equipamento % não encontrado', NEW.equipamento_id;
    END IF;

    IF NEW.data_devolucao IS NULL AND v_status IN ('manutencao', 'baixado') THEN
        RAISE EXCEPTION 'Equipamento % não pode ser emprestado: status %',
            NEW.equipamento_id, v_status;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_item_emprestimo ON itens_emprestimo;
CREATE TRIGGER trg_validar_item_emprestimo
BEFORE INSERT OR UPDATE OF equipamento_id, data_devolucao ON itens_emprestimo
FOR EACH ROW EXECUTE FUNCTION elocampus_validar_item_emprestimo();

