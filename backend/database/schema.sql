-- =========================================
-- 1. TABELA DE USUARIOS DO SISTEMA
-- =========================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    papel VARCHAR(20) NOT NULL DEFAULT 'operador',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (papel IN ('admin', 'operador'))
);


-- =========================================
-- 2. TABELA DE SOLICITANTES
-- =========================================

CREATE TABLE solicitantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    setor VARCHAR(100),
    email VARCHAR(150),
    telefone VARCHAR(30),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================
-- 3. TABELA DE CATEGORIAS
-- =========================================

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    descricao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);


-- =========================================
-- 4. TABELA DE EQUIPAMENTOS
-- =========================================

CREATE TABLE equipamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    numero_patrimonio VARCHAR(60) UNIQUE,
    categoria_id BIGINT NOT NULL
        REFERENCES categorias(id),
    setor VARCHAR(100),
    localizacao VARCHAR(150),
    estado_conservacao VARCHAR(30) NOT NULL DEFAULT 'bom',
    status VARCHAR(30) NOT NULL DEFAULT 'disponivel',
    qr_code VARCHAR(255),
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (
        estado_conservacao IN (
            'novo', 'bom', 'regular', 'danificado'
        )
    ),
    CHECK (
        status IN (
            'disponivel', 'emprestado',
            'manutencao', 'baixado'
        )
    )
);


-- =========================================
-- 5. TABELA DE EMPRESTIMOS
-- =========================================

CREATE TABLE emprestimos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id BIGINT NOT NULL
        REFERENCES solicitantes(id),
    usuario_responsavel_id BIGINT NOT NULL
        REFERENCES usuarios(id),
    data_emprestimo TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_prevista_devolucao TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'em_andamento',
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (
        status IN (
            'em_andamento', 'concluido', 'cancelado'
        )
    ),
    CHECK (data_prevista_devolucao >= data_emprestimo)
);


-- =========================================
-- 6. TABELA DE ITENS DO EMPRESTIMO
-- =========================================

CREATE TABLE itens_emprestimo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emprestimo_id BIGINT NOT NULL
        REFERENCES emprestimos(id),
    equipamento_id BIGINT NOT NULL
        REFERENCES equipamentos(id),
    data_devolucao TIMESTAMPTZ,
    estado_na_retirada VARCHAR(30),
    estado_na_devolucao VARCHAR(30),
    observacoes TEXT,

    UNIQUE (emprestimo_id, equipamento_id)
);


-- =========================================
-- 7. TABELA DE MANUTENCOES
-- =========================================

CREATE TABLE manutencoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL
        REFERENCES equipamentos(id),
    usuario_responsavel_id BIGINT
        REFERENCES usuarios(id),
    descricao_problema TEXT NOT NULL,
    data_abertura TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_conclusao TIMESTAMPTZ,
    status VARCHAR(30) NOT NULL DEFAULT 'aberta',
    solucao TEXT,
    observacoes TEXT,

    CHECK (
        status IN ('aberta', 'em_andamento', 'concluida')
    )
);


-- =========================================
-- 8. TABELA DE HISTORICO DE MOVIMENTACOES
-- =========================================

CREATE TABLE historico_movimentacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id BIGINT NOT NULL
        REFERENCES equipamentos(id),
    usuario_id BIGINT
        REFERENCES usuarios(id),
    emprestimo_id BIGINT
        REFERENCES emprestimos(id),
    tipo_movimentacao VARCHAR(40) NOT NULL,
    data_movimentacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    descricao TEXT
);


-- =========================================
-- 9. TABELA DE RESERVAS (OPCIONAL)
-- =========================================

CREATE TABLE reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id BIGINT NOT NULL
        REFERENCES solicitantes(id),
    usuario_responsavel_id BIGINT
        REFERENCES usuarios(id),
    data_inicio TIMESTAMPTZ NOT NULL,
    data_fim TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pendente',
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CHECK (data_fim > data_inicio),
    CHECK (
        status IN (
            'pendente', 'aprovada', 'rejeitada',
            'cancelada', 'concluida'
        )
    )
);


-- =========================================
-- 10. TABELA DE ITENS DAS RESERVAS
-- =========================================

CREATE TABLE itens_reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL
        REFERENCES reservas(id),
    equipamento_id BIGINT NOT NULL
        REFERENCES equipamentos(id),

    UNIQUE (reserva_id, equipamento_id)
);
